import { useState } from 'react';
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { useNavigate } from 'react-router-dom';
import toast from 'react-hot-toast';
import { Database, Library, Save, Sparkles, Wand2 } from 'lucide-react';
import { roadmapApi } from '../../services/api';
import { getErrorMessage, getFieldErrors } from '../../lib/http';
import { Alert, Badge, Button, ChipsField, SelectField, Switch, TextField } from '../ui';
import { RoadmapMeta, RoadmapTimeline } from './RoadmapParts';

const SOURCE = {
  ai: { label: 'Generated by AI', icon: Sparkles, tone: 'accent' },
  cache: { label: 'AI · served from cache (free)', icon: Database, tone: 'accent' },
  library: { label: 'Curated library', icon: Library, tone: 'primary' },
};
const PROVIDER = { groq: 'Groq', gemini: 'Gemini', openai: 'OpenAI', 'library-blend': 'library blend' };
const FIELD_IDEAS = ['Web development', 'Data analytics', 'Digital marketing', 'Human resources', 'Finance', 'UI/UX design', 'Cybersecurity', 'Product management', 'Mechanical design', 'Government exams', 'Content writing', 'Cloud computing', 'Machine learning', 'Business analysis', 'Supply chain', 'Sales'];

/** AI roadmap planner — any field or combination of fields, with zero-cost fallbacks. */
export function AiPlanner() {
  const qc = useQueryClient();
  const navigate = useNavigate();
  const { data: lib } = useQuery({ queryKey: ['roadmaps', 'list', '', ''], queryFn: () => roadmapApi.list() });
  const [form, setForm] = useState({ fields: [], level: 'beginner', hoursPerWeek: '10', timelineMonths: '6', goal: '', forceAI: false });
  const [errors, setErrors] = useState({});
  const [result, setResult] = useState(null);

  const generate = useMutation({
    mutationFn: () => roadmapApi.generate({ ...form, hoursPerWeek: Number(form.hoursPerWeek), timelineMonths: Number(form.timelineMonths) }),
    onSuccess: (res) => {
      setResult(res.data);
      setErrors({});
      setTimeout(() => document.getElementById('planner-result')?.scrollIntoView({ behavior: 'smooth' }), 50);
    },
    onError: (err) => {
      setErrors(getFieldErrors(err));
      toast.error(getErrorMessage(err));
    },
  });

  const save = useMutation({
    mutationFn: () => (result.libraryRoadmapId ? roadmapApi.enroll(result.libraryRoadmapId) : roadmapApi.saveDraft(result.draftKey)),
    onSuccess: (res) => {
      toast.success(res.message);
      qc.invalidateQueries({ queryKey: ['enrollments'] });
      qc.invalidateQueries({ queryKey: ['student-dashboard'] });
      const slug = result.libraryRoadmapId ? result.roadmap.slug : res.data.roadmap.slug;
      navigate(`/app/roadmap/${slug}`);
    },
    onError: (err) => toast.error(getErrorMessage(err)),
  });

  const set = (k, v) => setForm((f) => ({ ...f, [k]: v }));
  const src = result && SOURCE[result.source];

  return (
    <div className="stack" style={{ '--gap': '20px' }}>
      <form
        className="card stack"
        style={{ maxWidth: 880 }}
        onSubmit={(e) => {
          e.preventDefault();
          generate.mutate();
        }}
        noValidate
      >
        <div>
          <h2 style={{ fontSize: '1.1rem' }} className="row">
            <Wand2 size={18} aria-hidden="true" /> AI roadmap planner
          </h2>
          <p className="small muted mb-0">
            Add one field or combine several (e.g. “Data analytics” + “Digital marketing”). We check our curated library first and reuse
            cached plans, so most requests cost nothing — and you always get a plan, even if AI is unavailable.
          </p>
        </div>
        <ChipsField
          label="Field(s) you're interested in"
          hint="Up to 4. Press Enter after each."
          value={form.fields}
          onChange={(v) => set('fields', v)}
          max={4}
          error={errors.fields}
          suggestions={[...FIELD_IDEAS, ...(lib?.data || []).map((r) => r.title)]}
        />
        <div className="form-grid">
          <SelectField label="Current level" value={form.level} onChange={(e) => set('level', e.target.value)} options={[{ value: 'beginner', label: 'Beginner' }, { value: 'intermediate', label: 'Intermediate' }, { value: 'advanced', label: 'Advanced' }]} />
          <SelectField label="Hours per week" value={form.hoursPerWeek} onChange={(e) => set('hoursPerWeek', e.target.value)} options={['5', '10', '15', '20', '30', '40']} />
          <SelectField label="Timeline" value={form.timelineMonths} onChange={(e) => set('timelineMonths', e.target.value)} options={[{ value: '3', label: '3 months' }, { value: '6', label: '6 months' }, { value: '12', label: '1 year' }, { value: '24', label: '2 years' }]} />
        </div>
        <TextField label="Goal (optional)" placeholder="e.g. Get a data analyst internship in a startup" maxLength={160} value={form.goal} onChange={(e) => set('goal', e.target.value)} error={errors.goal} />
        <Switch label="Always generate a fresh AI plan" description="Off = use a matching curated roadmap when one exists (faster, free)." checked={form.forceAI} onChange={(v) => set('forceAI', v)} />
        <div>
          <Button type="submit" variant="primary" icon={Sparkles} loading={generate.isPending} disabled={!form.fields.length}>
            {generate.isPending ? 'Building your roadmap…' : 'Generate roadmap'}
          </Button>
        </div>
      </form>

      {result && (
        <section id="planner-result" className="stack fade-in" style={{ '--gap': '16px' }} aria-live="polite">
          {result.notice && <Alert type="info">{result.notice}</Alert>}
          <div className="card">
            <div className="row-between" style={{ alignItems: 'flex-start' }}>
              <div>
                <Badge tone={src.tone} icon={src.icon}>
                  {src.label}
                  {result.provider && result.source !== 'library' ? ` · ${PROVIDER[result.provider] || result.provider}` : ''}
                </Badge>
                <h2 className="mt-1 mb-0">{result.roadmap.title}</h2>
                <p className="muted small mt-1 mb-0">{result.roadmap.summary}</p>
                {result.roadmap.duration && <p className="xs subtle mb-0">Suggested duration: {result.roadmap.duration}</p>}
              </div>
              <Button variant="primary" icon={Save} loading={save.isPending} onClick={() => save.mutate()}>
                {result.libraryRoadmapId ? 'Follow this roadmap' : 'Save to my roadmaps'}
              </Button>
            </div>
          </div>
          <RoadmapMeta roadmap={result.roadmap} />
          <div className="card">
            <RoadmapTimeline roadmap={result.roadmap} />
          </div>
          <p className="xs subtle">AI suggestions can be imperfect — review resources and discuss your plan with a mentor.</p>
        </section>
      )}
    </div>
  );
}
